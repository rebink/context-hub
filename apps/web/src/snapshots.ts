import { ApiError, api } from "./api.js";
import type { GraphVersion, ProjectRole } from "./graph-helpers.js";
import { buildSnapshotRequest, canCreateSnapshot } from "./snapshot-helpers.js";

type Project = { id: string; role: ProjectRole };
type Options = { onUnauthorized(): void };
type Artifact = {
  id: string;
  name: string;
  type: string;
  currentVersion: number;
  freshness: { state: string };
};
type Snapshot = {
  id: string;
  projectId: string;
  name: string;
  gitSha: string;
  artifactCount: number;
  createdBy: string;
  createdAt: string;
  graph: {
    version: number;
    sourceCommitSha: string;
    storageLayout: string;
    publicationId: string | null;
    publishedAttempt: number;
    publishedLeaseId: string;
    uploadId: string;
    checksum: string;
    byteSize: number;
    contentType: string;
    repository: {
      provider: string;
      providerRepositoryId: string;
      owner: string;
      name: string;
      canonicalUrl: string;
    };
    graphifyVersion: string;
    adapterVersion: string;
    profile: string;
    formatVersion: number;
    generator: string;
    generatedBy: string;
    generatedAt: string;
  };
  manifest: { checksum: string; byteSize: number; contentType: string };
};
export type SnapshotArtifactProvenance = {
  artifactId: string;
  version: number;
  type: string;
  checksum: string;
  byteSize: number;
  contentType: string;
  uploadId: string;
  sourceCommitSha: string | null;
  changeNote: string | null;
  createdBy: string;
  createdAt: string;
};
type SnapshotDetail = { snapshot: Snapshot; artifacts: SnapshotArtifactProvenance[] };

